-- ------------------------------------------------------------
-- 金融機関名の桁を広げる
--   「ウォーターほ銀行」が8文字で varchar(7) に入らない。
--   bank_master を広げるだけでは、登録・振込のときに切り詰められるので
--   保存先の列も同時に広げる（片方だけだとSQLエラーになる）。
-- ------------------------------------------------------------
ALTER TABLE bank_master        MODIFY COLUMN bankName VARCHAR(20) NOT NULL;
ALTER TABLE bankTransfer_table MODIFY COLUMN bankName VARCHAR(20) NULL;
ALTER TABLE payee              MODIFY COLUMN bankName VARCHAR(20) NOT NULL;

-- ------------------------------------------------------------
-- 振込手数料を記録する
--   money は「相手が受け取る額」。口座から引かれるのは money + fee。
--   手数料を残さないと、後から記録を見ても引かれた額が復元できない。
-- ------------------------------------------------------------
ALTER TABLE bankTransfer_table
    ADD COLUMN fee INT NULL AFTER money;

UPDATE bankTransfer_table SET fee = 0 WHERE fee IS NULL;

-- ------------------------------------------------------------
-- デモ用の金融機関
--   0177 が自行（このアプリを動かしている銀行）。自行あては手数料が無料。
--   既存の AAA〜FFF 銀行は消さず、一覧から外すだけにする（検索では出る）。
-- ------------------------------------------------------------
UPDATE bank_master SET isMajor = 0;

INSERT INTO bank_master (bankCode, bankName, isMajor) VALUES
    ('0177', 'ふくよか銀行',     1),
    ('0008', '丸菱USJ銀行',     1),
    ('0009', '二井往友銀行',     1),
    ('0010', 'ウォーターほ銀行', 1)
ON DUPLICATE KEY UPDATE bankName = VALUES(bankName), isMajor = VALUES(isMajor);

